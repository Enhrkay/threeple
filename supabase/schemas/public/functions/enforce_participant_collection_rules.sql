CREATE OR REPLACE FUNCTION public.enforce_participant_collection_rules()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_policy text;
  v_expected_count integer;
  v_calculated_amount numeric(18,2);
  v_default_amount numeric(18,2);
  v_collection_status text;
  v_archived_at timestamptz;
  v_active_count integer;
begin
  select
    c.contribution_amount_policy,
    c.expected_participant_count,
    c.calculated_contribution_amount,
    c.default_amount,
    c.status,
    c.archived_at
  into
    v_policy,
    v_expected_count,
    v_calculated_amount,
    v_default_amount,
    v_collection_status,
    v_archived_at
  from public.collections c
  where c.id = new.collection_id;

  if not found then
    raise exception 'Collection not found.';
  end if;

  if v_archived_at is not null then
    raise exception 'This collection is archived and cannot accept participants.';
  end if;

  -- ----------------------------------------------------------
  -- EQUAL-SHARE TARGET
  -- ----------------------------------------------------------
  if v_policy = 'calculated_equal_share' then

    if v_expected_count is null or v_expected_count <= 0 then
      raise exception
        'Equal-share collection does not have a valid participant capacity.';
    end if;

    if v_calculated_amount is null or v_calculated_amount <= 0 then
      raise exception
        'Equal-share collection does not have a valid calculated contribution.';
    end if;

    -- Capacity only needs to be re-evaluated when a row is newly consuming
    -- an active participant slot.
    if new.is_active = true
       and (
         tg_op = 'INSERT'
         or old.is_active = false
         or old.collection_id is distinct from new.collection_id
       )
    then
      select count(*)::integer
      into v_active_count
      from public.participants p
      where p.collection_id = new.collection_id
        and p.is_active = true;

      if v_active_count >= v_expected_count then
        raise exception
          'This collection is full. All % participant slots have been taken.',
          v_expected_count;
      end if;
    end if;

    -- Browser/user input cannot override the organizer's economics.
    new.expected_amount := v_calculated_amount;

  -- ----------------------------------------------------------
  -- FIXED PER PERSON
  -- ----------------------------------------------------------
  elsif v_policy = 'fixed_per_person' then

    if v_default_amount is null or v_default_amount <= 0 then
      raise exception
        'Fixed-per-person collection does not have a valid contribution amount.';
    end if;

    new.expected_amount := v_default_amount;

  -- ----------------------------------------------------------
  -- FLEXIBLE
  -- ----------------------------------------------------------
  elsif v_policy = 'flexible' then

    if new.expected_amount is not null and new.expected_amount <= 0 then
      raise exception
        'Participant contribution amount must be greater than zero.';
    end if;

  -- ----------------------------------------------------------
  -- SCHEDULE-BASED
  -- Rotational/recurring obligations will be generated by the
  -- cycle engine later. We deliberately do not overwrite here.
  -- ----------------------------------------------------------
  elsif v_policy = 'schedule_based' then
    null;

  else
    raise exception
      'Collection contribution policy is not configured correctly.';
  end if;

  return new;
end;
$function$;

GRANT EXECUTE ON FUNCTION "public"."enforce_participant_collection_rules"() TO PUBLIC;

